nome = "Jhonatan Pinheiro"

print(nome[0])       # Acessa o primeiro caractere da string
print(nome[:9])      # Acessa os caracteres do início até o índice 8
print(nome[10:])     # Acessa do índice 10 até o final da string
print(nome[10:16])   # Acessa do índice 10 até o índice 15
print(nome[10:16:2]) # Acessa do índice 10 ao 15, pulando de 2 em 2
print(nome[:])       # Acessa todos os caracteres da string
print(nome[::-1])    # Inverte a string, percorrendo os caracteres de trás para frente