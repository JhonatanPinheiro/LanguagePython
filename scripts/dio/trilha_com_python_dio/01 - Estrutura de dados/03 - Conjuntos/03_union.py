conjunto_a = {1, 2}  # Cria o primeiro conjunto
conjunto_b = {3, 4}  # Cria o segundo conjunto

resultado = conjunto_a.union(conjunto_b)  # Une os elementos dos dois conjuntos

print(resultado)  # {1, 2, 3, 4}

# Observação: union() não altera os conjuntos originais; ele retorna um novo conjunto com os elementos dos dois.