numeros = {1, 2, 3, 1, 2, 4, 5, 5, 6, 7, 8, 9, 0}  # Cria um set; valores repetidos são eliminados

print(1 in numeros)  # Verifica se o número 1 existe no set; resultado: True
print(10 in numeros)  # Verifica se o número 10 existe no set; resultado: False

# Observação: o operador "in" verifica se um elemento está presente no set e retorna True ou False.