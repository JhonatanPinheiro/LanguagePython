sorteio = {1, 23}  # Cria um conjunto com os valores 1 e 23
print(sorteio)  # Exibe o conjunto → {1, 23}

sorteio.copy()  # Cria uma cópia do conjunto, mas a cópia não é armazenada
print(sorteio)  # Exibe o conjunto original → {1, 23}

# Observação: copy() cria um novo set, mas é necessário armazená-lo em uma variável para poder utilizá-lo depois.