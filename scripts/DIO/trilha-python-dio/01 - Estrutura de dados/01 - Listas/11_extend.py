linguagens = ["python", "js", "c"]  # Cria uma lista com três linguagens
print(linguagens)  # Exibe a lista: ["python", "js", "c"]

linguagens.extend(["java", "csharp"])  # Adiciona os elementos "java" e "csharp" ao final da lista
print(linguagens)  # Exibe a lista atualizada: ["python", "js", "c", "java", "csharp"]