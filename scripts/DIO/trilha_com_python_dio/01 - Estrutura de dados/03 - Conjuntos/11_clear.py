sorteio = {1, 23}  # Cria um conjunto com os valores 1 e 23
print(sorteio)  # Exibe o conjunto → {1, 23}

sorteio.clear()  # Remove TODOS os elementos do conjunto
print(sorteio)  # Exibe o conjunto vazio → set()

# Observação: clear() remove todos os elementos do set, mas o conjunto continua existindo como um set vazio.